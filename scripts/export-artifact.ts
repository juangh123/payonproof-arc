/**
 * Exports the ABI and creation bytecode of PayOnProofJobs from the current forge build into
 * committed files under src/generated, so the web build (e.g. on Vercel, which has no Foundry)
 * never reads contracts/out.
 *
 *   forge build && bun run export-artifact
 *
 * Writes:
 *   src/generated/PayOnProofJobs.json  abi + creation bytecode + provenance (canonical)
 *   src/generated/PayOnProofJobs.ts    the ABI as a typed `as const` value, used by the app
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { keccak256 } from 'viem'

const NAME = 'PayOnProofJobs'
const source = `contracts/out/${NAME}.sol/${NAME}.json`
if (!existsSync(source)) {
  console.error(`Missing ${source}. Run "forge build" first.`)
  process.exit(1)
}

const artifact = JSON.parse(readFileSync(source, 'utf8')) as {
  abi: unknown[]
  bytecode: { object: string }
  metadata?: { compiler?: { version?: string }; settings?: { evmVersion?: string; optimizer?: unknown } }
}
const bytecode = artifact.bytecode.object
if (!/^0x[0-9a-fA-F]+$/.test(bytecode)) {
  console.error('The artifact has no creation bytecode (library placeholders or an empty build).')
  process.exit(1)
}

const out = {
  contractName: NAME,
  source: `contracts/${NAME}.sol`,
  compiler: artifact.metadata?.compiler?.version ?? null,
  evmVersion: artifact.metadata?.settings?.evmVersion ?? null,
  creationBytecodeKeccak256: keccak256(bytecode as `0x${string}`),
  abi: artifact.abi,
  bytecode,
}

mkdirSync('src/generated', { recursive: true })
writeFileSync('src/generated/PayOnProofJobs.json', JSON.stringify(out, null, 2) + '\n')
writeFileSync(
  'src/generated/PayOnProofJobs.ts',
  `// Generated by scripts/export-artifact.ts from "forge build". Do not edit by hand.
// Regenerate with: forge build && bun run export-artifact
import type { Hex } from 'viem'
import artifact from './PayOnProofJobs.json'

export const jobsAbi = ${JSON.stringify(artifact.abi, null, 2)} as const

/** Creation bytecode (constructor arguments are appended when deploying). */
export const jobsBytecode = artifact.bytecode as Hex
/** keccak256 of the creation bytecode, to compare against your own forge build. */
export const jobsBytecodeHash = artifact.creationBytecodeKeccak256 as Hex
`,
)
console.log(`Exported ${NAME}: ${(bytecode.length - 2) / 2} bytes of creation code, hash ${out.creationBytecodeKeccak256}`)
